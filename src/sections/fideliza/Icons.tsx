// Ícone dentro de um círculo (padrão da apresentação)
export function IconBadge({
  name,
  dark = false,
  accent = false,
  size = 'md',
}: {
  name: IconName
  dark?: boolean
  accent?: boolean
  size?: 'sm' | 'md'
}) {
  const color = accent ? 'bg-sol text-areia' : dark ? 'bg-lima text-restinga' : 'bg-restinga text-lima'
  const box = size === 'sm' ? 'h-9 w-9' : 'h-12 w-12'
  const icon = size === 'sm' ? 'h-[1.1rem] w-[1.1rem]' : 'h-6 w-6'
  return (
    <span className={`inline-flex shrink-0 items-center justify-center rounded-full ${box} ${color}`}>
      <Icon name={name} className={icon} />
    </span>
  )
}
